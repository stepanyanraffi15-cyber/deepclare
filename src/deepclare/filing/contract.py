"""The filed format itself: every element name, every sequence, every constant, every facet.

This is the one place in DeepClare that spells the customs contract out. Dossier 04 §0
is the framing and it is not negotiable: the element names, their order, their
cardinality, the namespaces and the empty-versus-absent rules belong to an external
customs system. Deviations fail import with one opaque message that names no field, no
line and no reason. Nothing here is a design.

## Where each half of this module comes from

**Structure is evidence.** Element names, their namespace prefixes and every child
sequence come from `observed`, generated by reading all 71 ground-truth declarations in
the evaluation corpus. Not one of them is typed by hand here: every name constant below
is passed through `_attested`, which fails at import if the name appears in no filing,
and `SEQUENCES` and `REPEATABLE` are the evidence module's own tables. An earlier
revision of this file guessed 18 names and 14 sequences from the field specification's
section order and every one of the guesses that mattered was wrong — the shipment
container was missing altogether, which alone made every emitted file unimportable.

**Representation is specification.** The fixed tokens (`IM`, `40`, `00`, `000`, the `OO`
preference marker), the number and date rules, the fixed-width code discipline and the
physical shape of the file are dossier 03 §6, and the corpus corroborates all of them.

Three of the format's properties look like mistakes and are not:

* **The misspellings are the contract.** `CounryName`, `ESADout_CUConsigment`,
  `Pakage*`/`Paking*` are the schema's own spellings and are reproduced character for
  character. Correcting one produces a rejected file.
* **Order is enforced even where presence is not.** Every complex type is a sequence.
  Two optional siblings in the wrong order rejected the whole file — the confirmed case
  is packaging quantity emitted after packaging type — and the message named no element.
* **Fixed-width codes are strings.** `00`, `000`, `055`, the eight-digit office code.
  Parsing one as a number and writing it back destroys it, and nothing but literal
  discipline holds the widths.

## Where the evidence overrules the specification

Three statements in dossier 03 §6 and §9 do not survive contact with the corpus, and the
corpus wins because it is the artefact the portal accepts:

* nesting depth is **six**, not five — every goods item's packing sub-block sits at six
  in all 71 filings;
* a goods description of up to 603 characters is attested, so the schema's 250 is not
  carried as a cap of any kind;
* the two shipment-level cost elements the specification records as present in 311 of
  311 filings appear in **none** of the 71, so their absence is no longer flagged.

One statement survives as an open question rather than a rule: §6 says absence is always
omission and self-closing elements are unattested, and 2 of the 71 filings carry an empty
self-closing consignor address. This module never writes one; `conformance` reports one
it reads as unconfirmed rather than as a violation.
"""

