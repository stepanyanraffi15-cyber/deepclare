def _attested(name: str) -> str:
    """A name, having confirmed a real filing carries it.

    The whole point of this indirection is that a name nobody has ever seen filed cannot
    reach the writer. The failure it prevents gives no diagnostic on the other side: an
    unknown element is rejected as wrong format, naming no element.
    """
    if name not in observed.NAMESPACE_PREFIX:
        raise ValueError(
            f"{name!r} appears in none of the {observed.CASE_COUNT} filings in the "
            "evidence base; regenerate `observed` from a filing that carries it rather "
            "than naming it here"
        )
    return name


def prefix_for(name: str) -> str:
    """The namespace prefix one element is written under."""
    prefix = observed.NAMESPACE_PREFIX.get(name)
    if prefix is None:
        raise ValueError(f"no filing in the evidence base carries an element {name!r}")
    return prefix


