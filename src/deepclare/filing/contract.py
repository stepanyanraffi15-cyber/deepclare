def facet_for(parent_name: str | None, local_name: str) -> Facet | None:
    """The facet for one leaf, resolved by parent first.

    Resolution order is deliberate. `Rate` means two different things in two different
    parents and a name-keyed lookup gets one of them wrong, so the parent-qualified entry
    always wins and the bare-name entry is only a fallback for leaves that genuinely mean
    the same thing wherever they appear.
    """
    keyed = FACETS.get((parent_name, local_name))
    if keyed is not None:
        return keyed
    return FACETS.get((None, local_name))


def _uncovered_leaves() -> tuple[str, ...]:
    """Every (container, leaf) the evidence attests and no facet describes.

    A leaf with no facet is a leaf nothing checks, which is the same silence the portal
    answers with. The evidence names every place a leaf can occur, so this is decidable
    rather than a matter of remembering.
    """
    return tuple(
        f"{parent}/{child}"
        for parent, children in SEQUENCES.items()
        for child in children
        if child in LEAVES and facet_for(parent, child) is None
    )


_UNCOVERED = _uncovered_leaves()
if _UNCOVERED:  # pragma: no cover - a construction error, caught at import
    raise ValueError(
        "these leaves are attested in the evidence base and no facet describes them, "
        f"so nothing would check their values: {', '.join(_UNCOVERED)}"
    )


